#!/usr/bin/env python3
"""Package msitarzewski/agency-agents as a Synaps plugin named `agency`.

    python3 agency/build_plugin.py --out ~/.synaps-cli/plugins/agency
    python3 agency/build_plugin.py --src /path/to/agency-agents --out DIR

Without --src it clones the pinned commit (PINNED below) into a temp dir.

Layout written (the shape Synaps resolves `plugin:agent` against):

    <out>/.synaps-plugin/plugin.json
    <out>/LICENSE, <out>/NOTICE                (agency-agents is MIT)
    <out>/skills/agency/SKILL.md               index: divisions, how to dispatch
    <out>/skills/<division>/SKILL.md           roster for one division
    <out>/skills/<division>/agents/<slug>.md   the specialist, unchanged

A session then dispatches a specialist with
    subagent(agent="agency:<slug>", task="...")

<out> must be a real directory inside the Synaps plugins dir, not a symlink to
somewhere else: `plugin:agent` resolution canonicalizes the plugin path and
refuses one that leaves the plugins dir.

Stdlib only. Rebuilding replaces <out> completely, but only if <out> is empty
or was written by this script (it carries a .agency-build marker).
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = "https://github.com/msitarzewski/agency-agents.git"
PINNED = "b859c515d813efcfc4755d3471dd9e7686c7706d"  # 2026-11-05
MARKER = ".agency-build"
SLUG_RE = re.compile(r"^[A-Za-z0-9_-]+$")
DESC_MAX = 220


def frontmatter(text):
    """Return the frontmatter as a dict of top-level scalar keys, or None."""
    if not text.startswith("---"):
        return None
    end = text.find("\n---", 3)
    if end < 0:
        return None
    out = {}
    for line in text[3:end].splitlines():
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_-]*):\s*(.*)$", line)
        if not m:
            continue
        v = m.group(2).strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
            v = v[1:-1]
        out[m.group(1)] = v
    return out if "name" in out else None


def one_line(s, n=DESC_MAX):
    s = " ".join(s.replace("|", "/").split())
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def yaml_str(s):
    return json.dumps(s, ensure_ascii=False)  # a JSON string is a valid YAML scalar


def collect(src):
    divisions = json.loads((src / "divisions.json").read_text())["divisions"]
    roster = {}
    seen = {}
    for div in sorted(divisions):
        agents = []
        for p in sorted((src / div).rglob("*.md")):
            fm = frontmatter(p.read_text(encoding="utf-8"))
            if fm is None:
                continue
            slug = p.stem
            if not SLUG_RE.match(slug):
                sys.exit(f"refusing agent with unsafe file name: {p}")
            if slug in seen:
                sys.exit(f"duplicate agent slug {slug}: {seen[slug]} and {p}")
            seen[slug] = p
            agents.append({
                "slug": slug,
                "name": fm.get("name", slug),
                "description": fm.get("description", ""),
                "emoji": fm.get("emoji", ""),
                "path": p,
            })
        if agents:
            roster[div] = {"label": divisions[div].get("label", div), "agents": agents}
    return roster


def write_plugin(src, out, commit):
    roster = collect(src)
    total = sum(len(d["agents"]) for d in roster.values())

    if out.exists():
        if out.is_symlink():
            sys.exit(f"{out} is a symlink; `plugin:agent` resolution would refuse it. Remove it first.")
        if any(out.iterdir()) and not (out / MARKER).exists():
            sys.exit(f"{out} exists and was not written by this script; refusing to replace it")
    tmp = out.with_name(out.name + ".building")
    if tmp.exists():
        shutil.rmtree(tmp)
    (tmp / ".synaps-plugin").mkdir(parents=True)

    (tmp / ".synaps-plugin" / "plugin.json").write_text(json.dumps({
        "name": "agency",
        "version": f"0.1.0+{commit[:7]}",
        "description": f"{total} specialist agents from msitarzewski/agency-agents, "
                       "dispatchable as subagents with agent=\"agency:<slug>\".",
        "author": "AgentLand Contributors (agency-agents); packaged by synaps-switch",
        "license": "MIT",
        "repository": "https://github.com/msitarzewski/agency-agents",
    }, indent=2) + "\n")
    shutil.copy(src / "LICENSE", tmp / "LICENSE")
    (tmp / "NOTICE").write_text(
        "The agent files under skills/*/agents/ are copied unchanged from\n"
        f"https://github.com/msitarzewski/agency-agents at commit {commit}\n"
        "(MIT License, Copyright (c) 2025 AgentLand Contributors; see LICENSE).\n"
        "The SKILL.md index and roster files are generated by synaps-switch\n"
        "agency/build_plugin.py.\n")
    (tmp / MARKER).write_text(commit + "\n")

    # Index skill.
    rows = "\n".join(
        f"| `agency:{div}` | {d['label']} | {len(d['agents'])} |"
        for div, d in roster.items())
    (tmp / "skills" / "agency").mkdir(parents=True)
    (tmp / "skills" / "agency" / "SKILL.md").write_text(f"""---
name: agency
description: {yaml_str(f"The Agency: {total} specialist agents (engineering, design, marketing, sales, finance, security, product, testing and more) you can dispatch as subagents. Load this to see the divisions, then load a division to pick a specialist.")}
---

# The Agency

{total} specialists from [agency-agents](https://github.com/msitarzewski/agency-agents)
(MIT), packaged for Synaps. Each one is a subagent with its own system prompt:
a persona, a process and the deliverables it produces.

## How to use a specialist

1. Load the division's skill (table below) to see its roster.
2. Dispatch the specialist by slug:

   ```
   subagent_start(agent="agency:<slug>", task="<what you need, with all the context>")
   ```

   or `subagent(...)` for a blocking call. The specialist starts with no memory of
   this conversation: put everything it needs in `task`.
3. Collect the result and use it. You stay responsible for the outcome: review what
   a specialist hands back before acting on it.

Pick the narrowest specialist that fits. Two specialists in parallel on different
angles (say, a security reviewer and a performance reviewer on one change) is often
better than one generalist.

## Divisions

| Skill | Division | Specialists |
|---|---|---|
{rows}
""")

    # One skill per division.
    for div, d in roster.items():
        sdir = tmp / "skills" / div
        (sdir / "agents").mkdir(parents=True)
        names = ", ".join(a["name"] for a in d["agents"][:6])
        more = f" and {len(d['agents']) - 6} more" if len(d["agents"]) > 6 else ""
        lines = []
        for a in d["agents"]:
            shutil.copy(a["path"], sdir / "agents" / f"{a['slug']}.md")
            emoji = f"{a['emoji']} " if a["emoji"] else ""
            lines.append(f"| `agency:{a['slug']}` | {emoji}{one_line(a['name'], 60)} | {one_line(a['description'])} |")
        (sdir / "SKILL.md").write_text(f"""---
name: {div}
description: {yaml_str(f"Agency {d['label']} division: {len(d['agents'])} specialist subagents ({names}{more}). Load to see the roster and dispatch one with agent=agency:<slug>.")}
---

# Agency: {d['label']}

Dispatch with `subagent_start(agent="agency:<slug>", task="...")`. The specialist
starts cold, so give it the full context in `task`.

| Agent | Name | What it does |
|---|---|---|
""" + "\n".join(lines) + "\n")

    if out.exists():
        shutil.rmtree(out)
    tmp.rename(out)
    return roster, total


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", required=True, type=Path,
                    help="plugin dir to write, e.g. ~/.synaps-cli/plugins/agency")
    ap.add_argument("--src", type=Path, help="existing agency-agents checkout (default: clone the pinned commit)")
    ap.add_argument("--commit", default=PINNED, help="commit to clone when --src is not given")
    args = ap.parse_args()
    out = args.out.expanduser()

    with tempfile.TemporaryDirectory() as td:
        if args.src:
            src = args.src.expanduser()
            commit = subprocess.run(["git", "-C", str(src), "rev-parse", "HEAD"],
                                    capture_output=True, text=True).stdout.strip() or "unknown"
        else:
            src = Path(td) / "agency-agents"
            subprocess.run(["git", "init", "-q", str(src)], check=True)
            subprocess.run(["git", "-C", str(src), "fetch", "-q", "--depth", "1", REPO, args.commit], check=True)
            subprocess.run(["git", "-C", str(src), "checkout", "-q", "FETCH_HEAD"], check=True)
            commit = args.commit
        roster, total = write_plugin(src, out, commit)

    print(f"wrote {out}: {total} agents in {len(roster)} divisions (agency-agents {commit[:7]})")
    print('dispatch: subagent(agent="agency:<slug>", task="...")   index skill: agency:agency')


if __name__ == "__main__":
    main()
