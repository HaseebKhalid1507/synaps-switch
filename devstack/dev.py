def die(msg, code=1):
    print(f"dev.py: {msg}", file=sys.stderr)
    sys.exit(code)


def env():
    if not ENV.exists():
        die("no devstack/.env: run devstack/up.sh (or dev.py init-env)")
    out = {}
    for line in ENV.read_text().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, _, v = line.partition("=")
            out[k.strip()] = v.strip()
    return out


def api_url(e=None):
    e = e or env()
    return f"http://127.0.0.1:{e['API_HOST_PORT']}"


def mm_url(e=None):
    e = e or env()
    return f"http://127.0.0.1:{e['MATTERMOST_HOST_PORT']}"


def http(method, url, body=None, headers=None, timeout=45):
    data = None if body is None else json.dumps(body).encode()
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header("Accept", "application/json")
    if data is not None:
        req.add_header("Content-Type", "application/json")
    for k, v in (headers or {}).items():
        req.add_header(k, v)
    try:
        with _OPENER.open(req, timeout=timeout) as r:
            raw, code, hdrs = r.read(), r.status, r.headers
    except urllib.error.HTTPError as ex:
        raw, code, hdrs = ex.read(), ex.code, ex.headers
    except (urllib.error.URLError, OSError) as ex:
        return 0, {"error": type(ex).__name__}, {}
    try:
        payload = json.loads(raw) if raw else {}
    except ValueError:
        payload = {"raw": raw[:200].decode("utf-8", "replace")}
    return code, payload, hdrs


def init_env(_a):
    if ENV.exists():
        print("devstack/.env exists: kept")
        return
    h = lambda n: secrets.token_hex(n)  # noqa: E731
    text = ENV_TEMPLATE.format(db=h(24), dbo=h(24), reg=h(24), sk=h(32), gw=h(24), mma=h(24), mmu=h(24))
    fd = os.open(ENV, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(text)
    print("wrote devstack/.env (0600)")


def wait(_a, timeout=600):
    e = env()
    t0 = time.monotonic()
    for name, url in (("switch-core", api_url(e) + "/health"), ("mattermost", mm_url(e) + "/api/v4/system/ping")):
        while True:
            code, _, _ = http("GET", url, timeout=5)
            if code == 200:
                print(f"{name}: up ({time.monotonic() - t0:.0f}s)")
                break
            if time.monotonic() - t0 > timeout:
                die(f"{name} not healthy after {timeout}s ({url} -> {code})")
            time.sleep(2)


def gateway_cookie(e):
    code, body, hdrs = http("POST", api_url(e) + "/gateway/auth/login",
                            {"email": e["GATEWAY_ADMIN_EMAIL"], "password": e["GATEWAY_ADMIN_PASSWORD"]})
    if code != 200:
        die(f"gateway login -> {code} {body.get('detail', '')}")
    for c in hdrs.get_all("Set-Cookie") or []:
        if c.startswith("switch_auth="):
            return c.split(";", 1)[0]
    die("gateway login issued no switch_auth cookie")


def mint_token(a):
    if TOKEN.exists() and not a.force:
        print(f"{TOKEN.relative_to(HERE.parent)} exists: kept (--force mints another)")
        return
    e = env()
    cookie = gateway_cookie(e)
    code, body, _ = http("POST", api_url(e) + "/gateway/api-keys", {"label": "synaps-switch-dev"}, {"Cookie": cookie})
    if code != 200 or not body.get("key"):
        die(f"mint registration key -> {code} {body.get('detail', '')}")
    STATE.mkdir(mode=0o700, exist_ok=True)
    tmp = TOKEN.with_suffix(".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(body["key"])
    os.replace(tmp, TOKEN)
    print(f"minted a registration key (id {body.get('id')}, owner {e['GATEWAY_ADMIN_EMAIL']}) "
          f"-> {TOKEN.relative_to(HERE.parent)} (0600)")


def info(_a):
    e = env()
    print(json.dumps({
        "switch_version": e["SWITCH_VERSION"],
        "bridge_base_url": api_url(e),
        "gateway_url": f"http://127.0.0.1:{e['GATEWAY_HOST_PORT']}",
        "mattermost_url": mm_url(e),
        "mattermost_team": e["MATTERMOST_TEAM_NAME"],
        "mattermost_user": e["MATTERMOST_USER"],
        "gateway_admin": e["GATEWAY_ADMIN_EMAIL"],
        "registration_token_file": str(TOKEN) if TOKEN.exists() else None,
        "passwords": "in devstack/.env (0600)",
    }, indent=1))


_mm_tokens = {}


def mm_token(e, who):
    if who in _mm_tokens:
        return _mm_tokens[who]
    user = e["MATTERMOST_ADMIN_USER"] if who == "admin" else e["MATTERMOST_USER"]
    pw = e["MATTERMOST_ADMIN_PASSWORD"] if who == "admin" else e["MATTERMOST_USER_PASSWORD"]
    code, body, hdrs = http("POST", mm_url(e) + "/api/v4/users/login", {"login_id": user, "password": pw})
    if code != 200:
        die(f"mattermost login as {who} -> {code} {body.get('message', '')}")
    _mm_tokens[who] = hdrs.get("Token")
    return _mm_tokens[who]


def mm(e, method, path, body=None, who="user"):
    code, out, _ = http(method, mm_url(e) + "/api/v4" + path, body,
                        {"Authorization": f"Bearer {mm_token(e, who)}"})
    if code not in (200, 201):
        die(f"mattermost {method} {path} -> {code} {out.get('message', '')}")
    return out


def channel_id(e, name, who="user"):
    team = mm(e, "GET", f"/teams/name/{e['MATTERMOST_TEAM_NAME']}", who=who)
    return mm(e, "GET", f"/teams/{team['id']}/channels/name/{name}", who=who)["id"]


DEV_BASE = Path(os.environ.get("SYNAPS_SWITCH_DEV_BASE", Path.home() / ".synaps-switch-dev"))


def scrub(text):
    """Evidence scrubber: every credential value we know of (devstack/.env secrets, minted tokens,
    agent API keys, the broker machine token) becomes [REDACTED]; bearer headers too; $HOME becomes ~."""
    vals = set()
    envf = HERE / ".env"
    if envf.exists():
        for line in envf.read_text().splitlines():
            k, _, v = line.partition("=")
            if re.search(r"PASS|SECRET|TOKEN|KEY", k):
                vals.add(v.strip().strip("'\""))
    files = list((HERE / "state").glob("*")) + list((DEV_BASE / "synaps-switch" / "agents").glob("*/credentials.json")) \
        + list((DEV_BASE / "broker").glob("*token*")) + list(DEV_BASE.glob("m*/agents/*/credentials.json")) \
        + list(DEV_BASE.glob("m*/transport/agents/*.json")) + list((HERE.parent / "company" / "state" / "agents").glob("*.json"))
    for f in files:
        try:
            s = f.read_text().strip()
        except OSError:
            continue
        try:
            d = json.loads(s)
        except ValueError:
            vals.add(s)
            continue
        if isinstance(d, dict):
            vals.update(str(v) for k, v in d.items() if "key" in k or "token" in k or "secret" in k)
    for v in sorted((v for v in vals if len(v) >= 6), key=len, reverse=True):
        text = text.replace(v, "[REDACTED]")
    text = re.sub(r"(?i)(bearer\s+)[A-Za-z0-9._~+/=-]{8,}", r"\1[REDACTED]", text)
    return text.replace(str(Path.home()), "~")


def mm_post(a):
    e = env()
    cid = channel_id(e, a.channel, a.who)
    post = mm(e, "POST", "/posts", {"channel_id": cid, "message": a.message, "root_id": a.root or ""}, who=a.who)
    print(json.dumps({"id": post["id"], "root_id": post.get("root_id"), "create_at": post["create_at"]}))


def mm_thread(a):
    e = env()
    cid = channel_id(e, a.channel)
    data = mm(e, "GET", f"/channels/{cid}/posts?per_page=200" + (f"&since={a.since}" if a.since else ""))
    users = {}
    out = []
    for p in sorted(data.get("posts", {}).values(), key=lambda p: p["create_at"]):
        uid = p["user_id"]
        if uid not in users:
            u = mm(e, "GET", f"/users/{uid}")
            users[uid] = u.get("username")
        out.append({"id": p["id"], "root_id": p.get("root_id") or None, "user": users[uid],
                    "message": p["message"], "create_at": p["create_at"], "type": p.get("type") or None})
    print(json.dumps(out, indent=1, ensure_ascii=False))


def mm_join(a):
    e = env()
    cid = channel_id(e, a.channel, "admin")
    me = mm(e, "GET", f"/users/username/{e['MATTERMOST_USER']}", who="admin")
    mm(e, "POST", f"/channels/{cid}/members", {"user_id": me["id"]}, who="admin")
    print(f"{e['MATTERMOST_USER']} is in ~{a.channel}")


def bridges(a):
    e = env()
    code, body, _ = http("GET", api_url(e) + "/gateway/collaborations", None, {"Cookie": gateway_cookie(e)})
    if code != 200:
        die(f"list bridges -> {code} {body.get('detail', '') if isinstance(body, dict) else ''}")
    for b in body:
        flag = " (default)" if b.get("is_default") else ""
        print(f"{b.get('bridge_type'):<11} {b.get('display_name')!r:<24} {b.get('status')}{flag}  id={b.get('bridge_id')}")


def connect_discord(a):
    e = env()
    token, guild = e.get("DISCORD_BOT_TOKEN", ""), e.get("DISCORD_GUILD_ID", "")
    if not token or not guild:
        die("set DISCORD_BOT_TOKEN and DISCORD_GUILD_ID in devstack/.env first (the file is 0600 and gitignored)")
    if not re.fullmatch(r"\d{15,22}", guild):
        die("DISCORD_GUILD_ID should be the numeric server id (Developer Mode -> right-click the server -> Copy Server ID)")
    cookie = gateway_cookie(e)
    code, body, _ = http("GET", api_url(e) + "/gateway/collaborations", None, {"Cookie": cookie})
    if code == 200 and any(b.get("bridge_type") == "discord" for b in body):
        print("a Discord connection already exists: kept (see `dev.py bridges`)")
        return
    req = {"bridge_type": "discord", "display_name": a.name, "set_as_default": a.default,
           "connection_config": {"bot_token": token, "guild_id": guild}}
    code, body, _ = http("POST", api_url(e) + "/gateway/collaborations", req, {"Cookie": cookie}, timeout=90)
    if code not in (200, 201):
        detail = body.get("detail", "") if isinstance(body, dict) else ""
        die(f"connect Discord -> {code} {str(detail)[:300]}")
    print(f"connected Discord server {guild} as {body.get('display_name')!r}: status {body.get('status')}"
          f"{', default for new rooms' if body.get('is_default') else ''} (id {body.get('bridge_id')})")
    print("next: post any message in a Discord channel to turn it into a room, then invite the agent there")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("init-env").set_defaults(fn=init_env)
    sub.add_parser("wait").set_defaults(fn=wait)
    s = sub.add_parser("mint-token")
    s.add_argument("--force", action="store_true")
    s.set_defaults(fn=mint_token)
    sub.add_parser("info").set_defaults(fn=info)
    s = sub.add_parser("mm-post")
    s.add_argument("channel")
    s.add_argument("message")
    s.add_argument("--root")
    s.add_argument("--as", dest="who", default="user", choices=("user", "admin"))
    s.set_defaults(fn=mm_post)
    s = sub.add_parser("mm-thread")
    s.add_argument("channel")
    s.add_argument("--since", type=int)
    s.set_defaults(fn=mm_thread)
    s = sub.add_parser("mm-join")
    s.add_argument("channel")
    s.set_defaults(fn=mm_join)
    sub.add_parser("bridges").set_defaults(fn=bridges)
    s = sub.add_parser("connect-discord")
    s.add_argument("--name", default="Discord")
    s.add_argument("--default", action="store_true", help="new rooms land on Discord")
    s.set_defaults(fn=connect_discord)
    a = p.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
