#!/usr/bin/env python3
"""devstack helper (stdlib only). Never prints a secret.

  dev.py init-env              write devstack/.env with fresh random secrets (once, 0600)
  dev.py wait                  wait for switch-core /health and Mattermost
  dev.py mint-token            log in to the Gateway as the seeded admin and mint a
                               registration key -> devstack/state/registration.token (0600)
  dev.py info                  URLs and non-secret settings
  dev.py mm-post CHANNEL MSG [--root POST_ID] [--as user|admin]
                               post to a Mattermost channel (team from .env) as a person
  dev.py mm-thread CHANNEL [--since MS]
                               dump a channel's posts (JSON: id, root_id, user, message, create_at)
  dev.py mm-join CHANNEL       add the seeded Mattermost user to a channel (admin)
  dev.py bridges               list Switch's messaging-app connections (type, name, status, default)
  dev.py connect-discord [--name NAME] [--default]
                               connect a Discord server: reads DISCORD_BOT_TOKEN and
                               DISCORD_GUILD_ID from devstack/.env; --default makes new
                               rooms land on Discord instead of Mattermost
"""
